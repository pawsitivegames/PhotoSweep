import fs from "node:fs/promises"
import path from "node:path"

const mode = process.env.PLASMO_PUBLIC_PHOTOSWEEP_ALLOW_DEV_ENTITLEMENT
const allowDev = mode === "1"
const includeDevKey = allowDev || mode === "test"
const output = path.resolve("lib/generated/build-flags.ts")

await fs.mkdir(path.dirname(output), { recursive: true })
const temporaryOutput = path.join(
  path.dirname(output),
  `.build-flags-${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2)}.tmp`
)
const contents =
  `// Generated by tools/write-build-flags.mjs. Do not edit.\n` +
  `export const ALLOW_DEV_ENTITLEMENT = ${allowDev}\n` +
  `export const DEV_ENTITLEMENT_STORAGE_KEY = ${includeDevKey ? '"photoSweepDevEntitlement"' : "undefined"}\n`

try {
  await fs.writeFile(temporaryOutput, contents, "utf8")
  // Rename is atomic on the same filesystem, so concurrent build/test setup
  // cannot leave a partially-written TypeScript module behind.
  await fs.rename(temporaryOutput, output)
} catch (error) {
  await fs.rm(temporaryOutput, { force: true }).catch(() => {})
  throw error
}
